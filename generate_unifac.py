def main():
    subgroups = []
    mg_of = []
    for mi, (_, subs) in enumerate(MAIN_GROUPS):
        for name, r, q in subs:
            subgroups.append((name, r, q))
            mg_of.append(mi)
    ng = len(subgroups)
    nmg = len(MAIN_GROUPS)
    # compact main-group interaction matrix (full nmg x nmg, symmetric handling via pairs)
    main_inter = [[0.0]*nmg for _ in range(nmg)]
    for m,n,amn,anm in MAIN_PAIRS:
        main_inter[m][n] = amn
        main_inter[n][m] = anm

    lines = []
    lines.append("/// The full Original UNIFAC main-group table (56 main groups, 119 subgroups)")
    lines.append("/// with published R_k/Q_k (Hansen et al. 1991; Wittig et al. 2003;")
    lines.append("/// Balslev & Abildskov 2002) and a large subset of the published binary")
    lines.append("/// interaction matrix Aij/Aji (DDBST, main groups 1-23 core).")
    lines.append("pub fn seed_group_table() -> GroupTable {")
    lines.append("    // (name, R_k, Q_k)")
    lines.append("    let groups: &[(&str, f64, f64)] = &[")
    for name, r, q in subgroups:
        lines.append(f'        ("{name}", {r:.4f}, {q:.3f}),')
    lines.append("    ];")
    lines.append("    let ng = groups.len();")
    lines.append("    let r: Vec<f64> = groups.iter().map(|g| g.1).collect();")
    lines.append("    let q: Vec<f64> = groups.iter().map(|g| g.2).collect();")
    lines.append("    // Main-group index of each subgroup.")
    lines.append(f"    let mg: [usize; {ng}] = [")
    # write mg_of in rows of 20
    for i in range(0, len(mg_of), 20):
        chunk = mg_of[i:i+20]
        lines.append("        " + ", ".join(str(x) for x in chunk) + ",")
    lines.append("    ];")
    lines.append(f"    // Main-group interaction matrix ({nmg}x{nmg}), Amn.")
    lines.append(f"    let main_inter: [[f64; {nmg}]; {nmg}] = [")
    for row in main_inter:
        lines.append("        [" + ", ".join(f"{v:.4f}" for v in row) + "],")
    lines.append("    ];")
    lines.append("    let mut inter = vec![vec![TdParam::default(); ng]; ng];")
    lines.append("    for i in 0..ng {")
    lines.append("        for j in 0..ng {")
    lines.append("            let a = main_inter[mg[i]][mg[j]];")
    lines.append("            if a != 0.0 {")
    lines.append("                inter[i][j] = TdParam::new(a, 0.0, 0.0);")
    lines.append("            }")
    lines.append("        }")
    lines.append("    }")
    lines.append("    GroupTable::new(r, q, inter).unwrap()")
    lines.append("}")
    print("\n".join(lines))

if __name__ == "__main__":
    main()
